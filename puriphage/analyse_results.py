"""
analyse_results.py

Functions for:

- Summarising read classifications
- Determining the most similar phage
- Evaluating the expected phage
- Exporting unmappable reads

This module consumes BLAST results generated by
run_blast.py.
"""

from collections import Counter
import os

from Bio import SeqIO

from .make_report import (
    append_prophage_summary,
)


def count_hits(
    blast_results,
    suspected_phage,
    host_list,
    prophage_list,
    sequence_lengths,
    min_percent_identity,
    prophage_output_file,
    sample_name
):
    """
    Classify reads into:

    - suspected phage
    - host
    - unmappable
    """

    suspected_phage_read_total = 0
    suspected_phage_bp_total = 0
    suspected_phage_coverage = 0

    host_read_total = 0
    host_bp_total = 0
    non_prophage_host_bp_total = 0
    prophage_bp_dict = {}

    unmappable_read_total = 0
    unmappable_bp_total = 0
    unmappable_reads = set()

    phage_length = 1 #prevent divisions by 0
    prophage_length = 1 #prevent divisions by 0
    host_length = 1 #prevent divisions by 0

    hit_list = []
    bp_number_dict = {}
    bp_matched_dict = {}

    for read_id, results in blast_results.items():

        #
        # Analyse the BLAST results. For each read in the Nanopore data,
        # identify which hits bypass the min_percent_identity (%id).
        # If multiple hits bypass the min_percent_identity, append
        # all that apply using a "/". Save only the sequence identifier in
        # the hit_list variable.
        #

        read_length = results[0]
        best_hit = "NA"

        if len(results) > 1:

            for result in results[1:]:

                if result["percent_identity"] >= min_percent_identity:

                    #
                    # Make a list of all hit_Ids that pass the minimal % identity requirement
                    #

                    if best_hit == "NA":
                        best_hit = result["hit_id"]
                    else:
                        best_hit += "/" + result["hit_id"]
                        
            
        if best_hit == "NA":

            #
            # No valid hit found for this contig.
            #

            unmappable_reads.add(read_id)

        #
        # best_hit now represents the blast-identified hit(s). To identify
        # the number of sequenced bp for each hit, consolidate all sequenced bp
        # with the same best_hit into one dictionary.
        #

        bp_number_dict[best_hit] = (
        bp_number_dict.get(best_hit, 0)
        + read_length
        )
            
        hit_list.append(best_hit) #List of all BLAST-identified matches, 1 per contig
        
    #
    # count all hits in hit_list, which contains all hits found (1 per read),
    # to identify how many reads there are which an identifcal hit.
    #

    counter = Counter(hit_list)

    for hits, read_total in counter.items():

        #
        # Count how many reads match to identifiabels of interest 
        #
        # Multiple hits can bypass minimal %id, so seek most likely match.
        #
        # Example:
        #     PhageA/PhageB
        #
        # Therefore substring matching is used.
        #
        
        suspected_phage_found = False
        prophage_found = False
        host_found = False
        bp_total = bp_number_dict.get(hits)

        hits = hits.split("/")

        # search for suspected phage
        if suspected_phage != None:
            
            if suspected_phage in hits:

                suspected_phage_read_total += read_total
                suspected_phage_bp_total += bp_total
                suspected_phage_found = True
                
        # Parse remaining reads to look for host DNA, and determine whether this also matches a prophage in that host.
        if not suspected_phage_found:
            for prophage in prophage_list:
                if prophage in hits:
                    # Prophage reads can match to more than one prophage.
                    prophage_found = True
                    prophage_bp_dict[prophage] = (
                    prophage_bp_dict.get(prophage, 0)
                    + bp_total
                    )
            for host in host_list:
                if host in hits:
                    host_found = True
            if host_found:
                host_read_total += read_total
                host_bp_total += bp_total
                if not prophage_found:
                    # If a minimum of 1 prophage is identified, it cannot count as non-prophage host.
                    non_prophage_host_bp_total += bp_total

        if not any([suspected_phage_found, host_found, prophage_found]):
            unmappable_read_total += read_total
            unmappable_bp_total += bp_total
                
    if suspected_phage is not None:
        phage_length = sequence_lengths["Phage"][suspected_phage]
        suspected_phage_coverage = suspected_phage_bp_total/phage_length

    for host in host_list:
        # There should only ever be one host, so if multiple are possible, use the biggest
        if sequence_lengths["Host"][host] > host_length: 
            host_length = sequence_lengths["Host"][host]
            host_coverage = host_bp_total/host_length
            
    mobilised_prophage_counter = 0
    for prophage in prophage_list:
        prophage_mobilised = determine_mobilised_prophages(
            prophage_output_file,
            sample_name,
            prophage,
            prophage_bp_dict,
            non_prophage_host_bp_total,
            sequence_lengths,
            host_length,
            host_coverage
            )
        if prophage_mobilised:
            mobilised_prophage_counter += 1
    
    suspected_phage_numbers = {
        "suspected_phage" : suspected_phage,
        "phage_length": phage_length,
        "phage_read_total" : suspected_phage_read_total,
        "phage_bp_total" : suspected_phage_bp_total,
        "coverage" : suspected_phage_coverage,
        "host_read_total" : host_read_total,
        "host_bp_total" : host_bp_total,
        "unmappable_read_total" : unmappable_read_total,
        "unmappable_bp_total" : unmappable_bp_total,
        "mobilised_prophages" :mobilised_prophage_counter
    }

    return (
        counter,
        bp_number_dict,
        unmappable_reads,
        suspected_phage_numbers,
    )

def determine_mobilised_prophages(
    output_file,
    sample_name,
    prophage,
    prophage_bp_dict,
    non_prophage_host_bp_total,
    sequence_lengths,
    host_length,
    host_coverage
    ):

    """
    Calculate coverage of prophage and host without
    prophage for all supplied hosts in host list.
    Determine the ratio these two. If the ratio > 5,
    prophage is considered to be mobilised.

    Returns number of mobilised prophages found.
    """
    prophage_mobilised = False
    
    if prophage in prophage_bp_dict.keys():
        #add least one prophage read found
        prophage_bp_total = prophage_bp_dict[prophage]
        prophage_coverage = prophage_bp_total/sequence_lengths["Prophage"][prophage]
    else:
        prophage_coverage = 0

    all_prophage_lengths = 0
    for identified_prophage in prophage_bp_dict.keys():
        #determine combined length of all prophage_hits
        all_prophage_lengths += sequence_lengths["Prophage"][identified_prophage]

    non_prophage_host_length = host_length-all_prophage_lengths
    
    if non_prophage_host_bp_total == 0:
        non_prophage_host_bp_total = 1 #prevent division by 0
    
    coverage_non_prophage_host = non_prophage_host_bp_total/non_prophage_host_length
    
    prophage_ratio = prophage_coverage/coverage_non_prophage_host
    
    if prophage_ratio > 5: #if prophage is found 5x more than expected, it is most likely mobilised
        prophage_mobilised = True

    append_prophage_summary(
        output_file,
        sample_name,
        prophage,
        prophage_coverage,
        coverage_non_prophage_host,
        host_coverage,
        prophage_ratio,
        prophage_mobilised
        )
    
    return prophage_mobilised


def process_expected_or_best_phage(
    expected_phage, #None if no phage is supplied
    sequence_lengths,
    assembly_name,
    blast_results,
    all_results_file,
    separator,
):
    """
    Determine the phage with the highest
    percent identity.

    Ties are broken using the number of
    mismatched residues.

    Remaining ties are reported as:
        phageA/phageB
    """

    if expected_phage == None:
        best_result = {
            "hit_id": "",
            "percent_identity": 0,
            "residues_mismatched": float("inf"),
        }
    else:
        best_result = {
            "hit_id": expected_phage,
            "percent_identity": 0,
            "residues_mismatched": sequence_lengths["Phage"][expected_phage],
        }

    lines = []

    for results in blast_results.values():

        for result in results[1:]:

            if result["hit_id"] != assembly_name:
                lines.append(
                    f'{assembly_name}'
                    f'{separator}'
                    f'{result["hit_id"]}'
                    f'{separator}'
                    f'{result["percent_identity"]:.2f}'
                    f'{separator}'
                    f'{result["residues_mismatched"]}\n'
                )

                if expected_phage == None: #no expected phage supplied
                    if result["percent_identity"] > best_result["percent_identity"]:

                        best_result = result.copy()

                    elif result["percent_identity"] == best_result["percent_identity"]:

                        if result["residues_mismatched"] < best_result["residues_mismatched"]:

                            best_result = result.copy()

                        elif result["residues_mismatched"] == best_result["residues_mismatched"]:

                            best_result["hit_id"] += f'/{result["hit_id"]}'
                else:
                    if result["hit_id"] == expected_phage:
                        best_result = result.copy()

    with open(all_results_file, "a") as file:
        file.writelines(lines)

    return best_result


def filter_file_by_read_id(
    outdir,
    raw_data_fastq_file,
    unmappable_reads,
):
    """
    Export unmappable reads to a FASTQ file.
    """

    basename = os.path.basename(raw_data_fastq_file)
    root, _ = os.path.splitext(basename)

    output_file = os.path.join(
        outdir,
        f"{root}_unmappable_reads.fastq"
    )

    with open(output_file, "w") as outfile:

        for record in SeqIO.parse(
            raw_data_fastq_file,
            "fastq",
        ):

            if record.id in unmappable_reads:

                SeqIO.write(
                    record,
                    outfile,
                    "fastq",
                )
